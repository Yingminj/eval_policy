import glob, numpy as np, pandas as pd
files=sorted(glob.glob("/mnt/robot_platform/datasets/tidy_up_stationery_le/batch_3/data/**/*.parquet",recursive=True))
df=pd.concat([pd.read_parquet(f) for f in files])
print("columns:", [c for c in df.columns if 'action' in c or 'state' in c or 'obs' in c])
A=np.stack(df["action"].to_numpy())
S=np.stack(df["observation.state"].to_numpy())
g=np.abs(A-S)
print(f"\n=== training set: |action[t] - observation.state[t]| ===")
print(f"all 16 dims : mean={g.mean():.5f} p95={np.percentile(g,95):.5f} max={g.max():.5f}")
print(f"arms  0-13  : mean={g[:,:14].mean():.5f} p95={np.percentile(g[:,:14],95):.5f}")
print(f"grippers    : mean={g[:,14:].mean():.5f} p95={np.percentile(g[:,14:],95):.5f}")
J=([f"L_j{i}" for i in range(1,8)]+[f"R_j{i}" for i in range(1,8)]+["L_grip","R_grip"])
print("\nper dim mean |action-state|:")
for i in range(16): print(f"  {J[i]:<8}{g[:,i].mean():.5f}")
